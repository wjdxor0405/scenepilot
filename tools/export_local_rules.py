"""Export what the Android app needs to run the first steps of an accident on the phone (start, consent, the safety
questions and the emergency notice), so they work without a connection.

The rules stay in Python. This script runs the server's own code (session.py, emergency.py and the view the API returns)
for every way the safety questions can be answered and writes the results as data: texts, decisions, the next question
and the screen each answer leads to. The app only ports the answer parsing (the same regular expressions, exported here)
and looks everything else up. tests/test_local_first.py fails when the file is out of date.

    uv run python tools/export_local_rules.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from scenepilot import emergency as em
from scenepilot import session as sm
from scenepilot.app import _view

OUT = Path(__file__).resolve().parents[1] / "android-app" / "native" / "local-rules.js"
LOCAL_STAGES = ("consent", "safety", "emergency")
VOLATILE = ("id", "created_at")


def _key(answers: dict) -> str:
    return "|".join(answers.get(q, "-") for q in em.QUESTION_IDS)


def _entry(s: sm.Session) -> dict:
    view = _view(s)
    entry = {
        "stage": s.stage.value,
        "emergency": view["session"]["emergency"],
        "safety_progress": view["safety_progress"],
        "next_question": sm._next_question_id(s) if s.stage is sm.Stage.SAFETY else None,
        "prompt": None if s.stage is sm.Stage.SAFETY else view["prompt"],   # a safety prompt depends on retries: see safety_prompts
    }
    if s.stage is sm.Stage.EMERGENCY:
        after = s.model_copy(deep=True)
        sm.acknowledge_emergency(after)
        entry["ack"] = {"stage": after.stage.value, "acked_triggers": after.acked_triggers, "prompt": _view(after)["prompt"]}
    return entry


def build() -> dict:
    base = sm.new_session()
    consent_view = _view(base)
    session_template = {k: v for k, v in consent_view["session"].items() if k not in VOLATILE}

    started = sm.new_session()
    sm.accept_consent(started)

    entries: dict[str, dict] = {}
    safety_prompts: dict[str, list[dict]] = {}

    def walk(s: sm.Session) -> None:
        entries[_key(s.safety_answers)] = _entry(s)
        if s.stage is not sm.Stage.SAFETY:
            return
        qid = sm._next_question_id(s)
        retry = s.model_copy(deep=True)
        retry.unparsed[qid] = 1
        safety_prompts[qid] = [_view(s)["prompt"], _view(retry)["prompt"]]
        for answer in em.Answer:
            nxt = s.model_copy(deep=True)
            sm.answer_safety(nxt, answer.value)
            walk(nxt)

    walk(started)

    signals = {name: {"pos": pos.pattern, "neg": neg.pattern} for name, (pos, neg) in em._SIGNALS.items()}
    rules = {
        "country": em.DEFAULT_COUNTRY,
        "local_stages": list(LOCAL_STAGES),
        "questions": list(em.QUESTION_IDS),
        "max_unparsed": sm.MAX_UNPARSED,
        "session_template": session_template,
        "static_view": {k: consent_view[k] for k in ("checklist", "photo_progress", "info_fields")},
        "consent": {"prompt": consent_view["prompt"], "safety_progress": consent_view["safety_progress"]},
        "safety_prompts": safety_prompts,
        "entries": entries,
        "parse": {
            "unsure": em._UNSURE.pattern,
            "signals": signals,
            "danger_parts": list(em._DANGER_PARTS),
            "no_words": sorted(em._NO_WORDS),
            "strong_yes": sorted(em._STRONG_YES),
            "weak_yes": sorted(em._WEAK_YES),
            "sound_alikes": {k: v.value for k, v in em._SOUND_ALIKES.items()},
            "plain": [a.value for a in em.Answer],
        },
    }
    rules["version"] = hashlib.sha256(json.dumps(rules, sort_keys=True).encode()).hexdigest()[:12]
    return rules


def render(rules: dict) -> str:
    return (
        "// Generated by tools/export_local_rules.py from the server's Python rules. Do not edit by hand.\n"
        '(typeof window !== "undefined" ? window : globalThis).SCENEPILOT_LOCAL_RULES = '
        + json.dumps(rules, indent=1, ensure_ascii=False)
        + ";\n"
    )


if __name__ == "__main__":
    OUT.write_text(render(build()), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
